#for output in float till two decimal places 
num1=float(input("enter first number :"))
num2=float(input("enter second number :"))
print("-"*100)
print(f"\t Arithmetic Operations Result")
print("-"*100)
print("\tSum of ({},{}) = {:.2f}".format(num1,num2,num1+num2))
print("\tSub of ({},{}) = {:.2f}".format(num1,num2,num1-num2))
print("\tMul of ({},{}) = {:.2f}".format(num1,num2,num1*num2))
print("\tDiv of ({},{}) = {:.2f}".format(num1,num2,num1/num2))
print("\tFloor Div of ({},{}) = {:.2f}".format(num1,num2,num1//num2))
print("\tModu of ({},{}) = {:.2f}".format(num1,num2,num1%num2))
print("\tExpo of ({},{}) = {:.2f}".format(num1,num2,num1**num2))
print("-"*100)